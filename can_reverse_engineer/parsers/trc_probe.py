"""TRC 파일의 header와 앞부분 메시지를 형식을 가정하지 않고 관찰한다 (REQ-01).

열 의미는 정하지 않는다. header의 범례와 각 열 토큰의 모양만 기록하고,
열 해석은 REQ-02 Parser가 이 관찰 결과를 근거로 정한다.
"""

import re
from collections import Counter
from typing import Any

_KEY_VALUE = re.compile(r"^;\$(\w+)=(.*)$")
_LABELLED = re.compile(r"^;\s*(Start time|Generated by)[:\s]\s*(.+)$")
_SEPARATOR = re.compile(r"^;[-+\s]+$")
_KINDS = (
    ("index", re.compile(r"^\d+\)$")),
    ("int", re.compile(r"^-?\d+$")),
    ("float", re.compile(r"^-?\d+\.\d+$")),
    ("hex", re.compile(r"^[0-9A-Fa-f]+$")),
)


def looks_like_trc(text: str) -> bool:
    lines = text.lstrip("\ufeff").splitlines()
    return bool(lines) and lines[0].startswith(";$FILEVERSION")


def _kind(token: str) -> str:
    return next((name for name, pattern in _KINDS if pattern.match(token)), "text")


def _legend(header: list[str]) -> list[str]:
    names = []
    for line in header:
        if _KEY_VALUE.match(line) or _LABELLED.match(line) or _SEPARATOR.match(line):
            continue
        name = line[1:].split("|")[-1].strip()
        if name:
            names.append(name)
    return names


def _column_profiles(rows: list[list[str]]) -> list[dict[str, Any]]:
    width = max((len(r) for r in rows), default=0)
    profiles = []
    for index in range(width):
        values = [r[index] for r in rows if len(r) > index]
        distinct = list(dict.fromkeys(values))
        profiles.append({
            "column": index + 1,
            "present_in": len(values),
            "distinct": len(distinct),
            "kinds": dict(Counter(_kind(v) for v in values)),
            "examples": distinct[:5],
        })
    return profiles


def probe_trc(text: str, sample_size: int = 50) -> dict[str, Any]:
    lines = text.lstrip("\ufeff").splitlines()
    header: list[str] = []
    for line in lines:
        if not line.startswith(";"):
            break
        header.append(line)
    rest = lines[len(header):]
    body = [line.strip() for line in rest if line.strip() and not line.startswith(";")]

    fields: dict[str, str] = {}
    for line in header:
        if match := _KEY_VALUE.match(line) or _LABELLED.match(line):
            fields[match[1]] = match[2].strip()

    sample = body[:sample_size]
    rows = [line.split() for line in sample]
    return {
        "header_line_count": len(header),
        "header_fields": fields,
        "column_legend": _legend(header),
        "data_line_count": len(body),
        "comment_lines_after_header": sum(1 for line in rest if line.startswith(";")),
        "sample_size": len(sample),
        "sample_lines": sample,
        "token_count_distribution": dict(Counter(len(r) for r in rows)),
        "column_profiles": _column_profiles(rows),
    }
