import json

from pypdf import PdfWriter

from can_reverse_engineer.parsers.inventory import build_inventory
from can_reverse_engineer.reports.inventory_report import write_outputs

TRC = ";$FILEVERSION=1.1\n;   Generated by PCAN-View v6.1\n     1)  1.0  Rx  07E4  8  03 22 01 01 00 00 00 00\n"


def _dataset(tmp_path):
    root = tmp_path / "inbox"
    (root / "src").mkdir(parents=True)
    (root / "a.trc").write_text(TRC, encoding="ascii")
    (root / "copy_of_a.txt").write_text(TRC, encoding="ascii")
    (root / "메모.txt").write_bytes("셀 전압 72개".encode("cp949"))
    (root / "ignored.bin").write_bytes(b"\x00\x01")
    (root / "src" / "bms.c").write_text("raw = (data[4] << 8) | data[5];\n", encoding="utf-8")
    writer = PdfWriter()
    writer.add_blank_page(width=595, height=842)
    with open(root / "report.pdf", "wb") as fh:
        writer.write(fh)
    return root


def test_inventory_classifies_by_extension_and_content(tmp_path):
    inventory = build_inventory(_dataset(tmp_path))
    files = {f["path"]: f for f in inventory["files"]}

    assert sorted(files) == ["a.trc", "copy_of_a.txt", "report.pdf", "src/bms.c", "메모.txt"]
    assert files["a.trc"]["purpose"] == "CAN 트레이스(TRC)"
    assert files["copy_of_a.txt"]["purpose"] == "CAN 트레이스(TRC)"
    assert files["copy_of_a.txt"]["purpose_basis"] == "파일 첫 줄이 ;$FILEVERSION"
    assert files["메모.txt"]["encoding"] == "cp949"
    assert files["a.trc"]["encoding"] == "ascii"
    assert files["report.pdf"]["encoding"] == "binary"
    assert files["a.trc"]["size"] == len(TRC)


def test_inventory_reports_trc_pdf_source_and_issues(tmp_path):
    inventory = build_inventory(_dataset(tmp_path))

    assert [t["path"] for t in inventory["trc"]] == ["a.trc", "copy_of_a.txt"]
    pdf = inventory["pdf"][0]
    assert pdf["page_count"] == 1
    assert pdf["text_layer"] == "없음"
    assert pdf["pages"][0]["width_mm"] == 209.9

    assert inventory["source_code"]["found"] is True
    assert inventory["source_code"]["files"] == [{"path": "src/bms.c", "lines": 1}]

    messages = [issue["message"] for issue in inventory["issues"]]
    assert any("내용이 같은 파일" in m and "copy_of_a.txt" in m for m in messages)
    assert any("텍스트 레이어가 없습니다" in m for m in messages)


def test_outputs_are_written(tmp_path):
    inventory = build_inventory(_dataset(tmp_path))
    out = tmp_path / "output"

    write_outputs(inventory, out)

    saved = json.loads((out / "file_inventory.json").read_text(encoding="utf-8"))
    assert saved["file_count"] == 5
    report = (out / "file_analysis.md").read_text(encoding="utf-8")
    for section in ("[FILES FOUND]", "[TRC STRUCTURE]", "[PDF STRUCTURE]", "[SOURCE CODE FOUND]",
                    "[ISSUES]", "[NEXT STEP]"):
        assert section in report


def test_missing_source_code_is_recorded(tmp_path):
    root = tmp_path / "only_trace"
    root.mkdir()
    (root / "a.trc").write_text(TRC, encoding="ascii")

    inventory = build_inventory(root)

    assert inventory["source_code"]["found"] is False
    assert any("소스코드가 없습니다" in i["message"] for i in inventory["issues"])
